-- Schema from the brief's "Database Setup".
-- Assumption: the brief names the table `timeDeposits` and the column `timeDepositId`. PostgreSQL folds unquoted
-- identifiers to lower case, so camelCase names would need quoting in every query. We use the snake_case
-- equivalents `time_deposits` and `time_deposit_id` (likewise `plan_type`).

create table time_deposits
(
    id        integer generated by default as identity primary key,
    plan_type varchar        not null,
    days      integer        not null,
    balance   numeric(19, 2) not null
);

create table withdrawals
(
    id              integer generated by default as identity primary key,
    time_deposit_id integer        not null references time_deposits (id),
    amount          numeric(19, 2) not null,
    date            date           not null
);
